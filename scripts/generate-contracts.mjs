import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(import.meta.dirname, "..");

export function contractPaths(args = process.argv.slice(2)) {
  const values = new Map();
  for (let index = 0; index < args.length; index += 2) {
    if (!args[index]?.startsWith("--") || args[index + 1] === undefined) {
      throw new Error("Expected --source or --target followed by a path.");
    }
    values.set(args[index], args[index + 1]);
  }
  return {
    source: path.resolve(values.get("--source") ?? path.join(root, "../ArquitecturaBaseMutitenant/docs/contracts/openapi.json")),
    target: path.resolve(values.get("--target") ?? path.join(root, "src/shared/api/generated/schema.d.ts")),
  };
}

export async function renderContracts(source) {
  if (!existsSync(source)) throw new Error(`OpenAPI contract not found: ${source}`);
  const schema = JSON.parse(readFileSync(source, "utf8"));
  const generated = astToString(await openapiTS(schema));
  return generated.endsWith("\n") ? generated : `${generated}\n`;
}

const limitKeys = ["minLength", "maxLength", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "maxItems"];

/** The limits of one property; a list also carries those of each element under `items` (each tag's maxLength). */
function limitsOf(definition) {
  const limits = Object.fromEntries(limitKeys.filter((key) => definition[key] !== undefined).map((key) => [key, definition[key]]));
  // int32 is a wire constraint even when no validator narrows its range.
  if (definition.format === "int32") {
    limits.minimum ??= -(2 ** 31);
    limits.maximum ??= 2 ** 31 - 1;
  }
  const items = definition.items && typeof definition.items === "object" && !definition.items.$ref ? limitsOf(definition.items) : {};
  if (Object.keys(items).length) limits.items = items;
  return limits;
}

/** Runtime restrictions extracted from the same OpenAPI used for TypeScript types. */
export function renderValidationContracts(source) {
  const schema = JSON.parse(readFileSync(source, "utf8"));
  const constraints = {};
  const enumValues = {};
  const enums = {};
  for (const [name, component] of Object.entries(schema.components?.schemas ?? {})) {
    // Un enum con nombre propio, en el orden en que lo declaró el back: el de su circuito, con el que ordena una tabla (264).
    if (Array.isArray(component.enum)) enums[name] = component.enum;
    const properties = {};
    const propertyEnums = {};
    for (const [property, definition] of Object.entries(component.properties ?? {})) {
      if (Array.isArray(definition.enum)) propertyEnums[property] = definition.enum;
      const limits = limitsOf(definition);
      if (Object.keys(limits).length) properties[property] = limits;
    }
    if (Object.keys(properties).length) constraints[name] = properties;
    if (Object.keys(propertyEnums).length) enumValues[name] = propertyEnums;
  }
  return `// Generated by npm run contracts. Do not edit.\nexport const validationConstraints = ${JSON.stringify(constraints, null, 2)} as const;\n\nexport const schemaEnumValues = ${JSON.stringify(enumValues, null, 2)} as const;\n\nexport const schemaEnums = ${JSON.stringify(enums, null, 2)} as const;\n\nexport const organizationAuditCategories = ${JSON.stringify(schema["x-organization-audit-categories"] ?? [])} as const;\n`;
}

export function validationTarget(target) {
  return path.join(path.dirname(target), "validation.ts");
}

/** Las acciones del asistente (ADR 0068) que el back publica junto al OpenAPI. */
export function assistantActionsSource(source) {
  return path.join(path.dirname(source), "assistant-actions.json");
}

export function assistantActionsTarget(target) {
  return path.join(path.dirname(target), "assistant-actions.ts");
}

// La forma la fija el back (AssistantActionContractWriter): enums en camelCase y sin nulls. Los tipos de campo son la
// lista cerrada de la ADR 0068 §4: un tipo nuevo del back rompe los tipos del front hasta que se sume acá.
const assistantActionTypes = `export type AssistantActionFieldType = "text" | "longText" | "integer" | "decimal" | "money" | "date" | "boolean" | "email"
  | "phone" | "taxId" | "choice" | "choices" | "record" | "consent" | "items";

export interface AssistantActionContractField {
  readonly name: string;
  readonly type: AssistantActionFieldType;
  readonly required: boolean;
  readonly maxLength?: number;
  readonly maxItems?: number;
  readonly minimum?: number;
  readonly maximum?: number;
  readonly dependsOn?: string;
  readonly itemKey?: string;
  readonly itemFields?: readonly AssistantActionContractField[];
}

export interface AssistantActionContract {
  readonly id: string;
  readonly version: number;
  readonly kind: "create" | "edit" | "remove";
  readonly requirement: { readonly kind: string; readonly permission: string; readonly organizationPermission?: string; readonly companyField?: string };
  readonly module?: string;
  readonly saveRoute: string;
  readonly confirmation: string;
  readonly screen: string;
  readonly effect: string;
  readonly target?: { readonly readRoute: string };
  readonly fieldsFromTarget: boolean;
  readonly fields: readonly AssistantActionContractField[];
}`;

export function renderAssistantActions(source) {
  const actions = JSON.parse(readFileSync(source, "utf8")).actions ?? [];
  const keys = actions.map((action) => `${action.id}@${action.version}`);
  return `// Generated by npm run contracts from assistant-actions.json. Do not edit.\n${assistantActionTypes}\n\n`
    + `export const assistantActions: readonly AssistantActionContract[] = ${JSON.stringify(actions, null, 2)};\n\n`
    + `/** Cada acción como \`<id>@<versión>\`, la clave de su adaptador. */\n`
    + `export const assistantActionKeys = ${JSON.stringify(keys, null, 2)} as const;\n\n`
    + `export type AssistantActionKey = (typeof assistantActionKeys)[number];\n`;
}

export async function generateContracts({ source, target }) {
  const generated = await renderContracts(source);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, generated, "utf8");
  writeFileSync(validationTarget(target), renderValidationContracts(source), "utf8");
  if (existsSync(assistantActionsSource(source))) {
    writeFileSync(assistantActionsTarget(target), renderAssistantActions(assistantActionsSource(source)), "utf8");
  }
  return target;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const target = await generateContracts(contractPaths());
    console.log(`Types generated: ${target}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
