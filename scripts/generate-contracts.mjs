import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(import.meta.dirname, "..");

export function contractPaths(args = process.argv.slice(2)) {
  const values = new Map();
  for (let index = 0; index < args.length; index += 2) {
    if (!args[index]?.startsWith("--") || args[index + 1] === undefined) {
      throw new Error("Expected --source or --target followed by a path.");
    }
    values.set(args[index], args[index + 1]);
  }
  return {
    source: path.resolve(values.get("--source") ?? path.join(root, "../ArquitecturaBaseMutitenant/docs/contracts/openapi.json")),
    target: path.resolve(values.get("--target") ?? path.join(root, "src/shared/api/generated/schema.d.ts")),
  };
}

export async function renderContracts(source) {
  if (!existsSync(source)) throw new Error(`OpenAPI contract not found: ${source}`);
  const schema = JSON.parse(readFileSync(source, "utf8"));
  const generated = astToString(await openapiTS(schema));
  return generated.endsWith("\n") ? generated : `${generated}\n`;
}

/** Runtime restrictions extracted from the same OpenAPI used for TypeScript types. */
export function renderValidationContracts(source) {
  const schema = JSON.parse(readFileSync(source, "utf8"));
  const constraints = {};
  for (const [name, component] of Object.entries(schema.components?.schemas ?? {})) {
    const properties = {};
    for (const [property, definition] of Object.entries(component.properties ?? {})) {
      const limits = Object.fromEntries(["minLength", "maxLength", "minimum", "maximum", "maxItems"]
        .filter((key) => definition[key] !== undefined).map((key) => [key, definition[key]]));
      // int32 is a wire constraint even when no validator narrows its range.
      if (definition.format === "int32") {
        limits.minimum ??= -(2 ** 31);
        limits.maximum ??= 2 ** 31 - 1;
      }
      if (Object.keys(limits).length) properties[property] = limits;
    }
    if (Object.keys(properties).length) constraints[name] = properties;
  }
  return `// Generated by npm run contracts. Do not edit.\nexport const validationConstraints = ${JSON.stringify(constraints, null, 2)} as const;\n\nexport const organizationAuditCategories = ${JSON.stringify(schema["x-organization-audit-categories"] ?? [])} as const;\n`;
}

export function validationTarget(target) {
  return path.join(path.dirname(target), "validation.ts");
}

export async function generateContracts({ source, target }) {
  const generated = await renderContracts(source);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, generated, "utf8");
  writeFileSync(validationTarget(target), renderValidationContracts(source), "utf8");
  return target;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const target = await generateContracts(contractPaths());
    console.log(`Types generated: ${target}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
